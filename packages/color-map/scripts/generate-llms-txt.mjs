// Generates llms.txt from the built CLI's command table, so it cannot describe a
// command that no longer exists. `--check` exits 1 when the file on disk differs.
import { readFileSync, writeFileSync } from 'node:fs'
import { commands } from '../bin/index.js'

const file = new URL('../llms.txt', import.meta.url)
const base = 'https://unpkg.com/color-map/schemas'

const optionNames = (c) => Object.keys(c.options ?? {}).map((o) => `--${o}`)
const argNames = (c) => (c.arguments ?? []).map((a) => (a.type?.isOptional ? `[${a.name}]` : `<${a.name}>`))

const lines = [
	'# color-map',
	'',
	'> The `color-map` command: convert, mix, contrast-check, scale and export CSS colors, and build a semantic palette whose text pairs all pass WCAG 2, from one brand color.',
	'',
	'This file is generated by `scripts/generate-llms-txt.mjs` from the command table. Do not edit it.',
	'',
	'Conventions that hold for every command:',
	'',
	'- Output is TOON on stdout by default; `--format json` gives JSON. Diagnostics go to stderr.',
	'- Colors are any CSS color string, including `color-mix()` and relative colors.',
	'- Contrast is WCAG 2. There is no other contrast algorithm.',
	'- `--full` adds every field. Empty results say so explicitly.',
	'- A failure exits 1 or 2 with `error`, `code` and `help` fields on stdout. Nothing prompts; unknown options fail.',
	'- Run it with `npx color-map <command>`, or install the `color-map` agent skill from this package.',
	'',
	'## Commands',
	'',
	...commands.map(
		(c) =>
			`- [${c.name}](${base}/${c.name}.schema.json): ${c.description}. Usage: \`color-map ${[c.name, ...argNames(c)].join(' ')}\` with ${optionNames(c).join(', ') || 'no options'}.`
	),
	'',
	'## Optional',
	'',
	'- [Source and README](https://github.com/cyberuni/color-map): the color-map library and CLI.',
	''
]
const text = lines.join('\n')

if (process.argv.includes('--check')) {
	let current = ''
	try {
		current = readFileSync(file, 'utf8')
	} catch {}
	if (current !== text) {
		console.error('llms.txt is out of date: run `pnpm llms`')
		process.exit(1)
	}
} else writeFileSync(file, text)
